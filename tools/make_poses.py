"""Turns the web port's reference poses into a C table for the BENCH=3 ROM. Usage: make_poses.py <poses.json>"""
import json, math, sys
poses = json.load(open(sys.argv[1]))
FX = 4096
with open('test/poses.h', 'w') as out, open('test/poses.txt', 'w') as txt:
    out.write('// Generated by tools/make_poses.py\nstatic const s32 POSES[][6]={\n')
    for p in poses:
        e, t = p['eye'], p['target']
        d = [t[i]-e[i] for i in range(3)]
        yaw = int(math.atan2(-d[0], -d[2])/(2*math.pi)*32768) & 0x7fff
        pitch = int(math.atan2(d[1], math.hypot(d[0], d[2]))/(2*math.pi)*32768)
        out.write('{%d,%d,%d,%d,%d,%d},\n' % (p['level'], e[0]*FX, e[1]*FX, e[2]*FX, yaw, pitch))
        txt.write('%d %s\n' % (p['level'], p['file']))
    out.write('};\n')
